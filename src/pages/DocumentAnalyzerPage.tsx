import { useState, useCallback, useRef } from 'react';
import { FileSearch, UploadCloud, X, FileText, Download, AlertTriangle, CheckCircle2, Loader2 } from 'lucide-react';
import { useLanguage } from '@/context/LanguageContext';
import { useToast } from '@/components/ui/Toast';
import { Card, CardBody } from '@/components/ui/Card';
import { Button } from '@/components/ui/Button';
import { Badge } from '@/components/ui/Badge';
import { PageHeader, EmptyState } from '@/components/ui/PageHeader';
import { DemoLabel } from '@/components/ui/Disclaimer';
import { extractTextFromFile, formatFileSize, downloadTextFile } from '@/utils/helpers';

interface AnalysisResult {
  fileName: string;
  fileSize: number;
  extractedText: string;
  summary: string;
  terms: string[];
  concerns: string[];
  ts: number;
}

const MAX_SIZE = 10 * 1024 * 1024;

export function DocumentAnalyzerPage() {
  const { t, isBn } = useLanguage();
  const { notify } = useToast();
  const [file, setFile] = useState<File | null>(null);
  const [dragOver, setDragOver] = useState(false);
  const [progress, setProgress] = useState(0);
  const [analyzing, setAnalyzing] = useState(false);
  const [result, setResult] = useState<AnalysisResult | null>(null);
  const [error, setError] = useState<string | null>(null);
  const inputRef = useRef<HTMLInputElement>(null);

  const handleFile = useCallback(
    (f: File) => {
      if (f.size > MAX_SIZE) {
        notify(isBn ? 'ফাইল ১০MB এর বেশি' : 'File exceeds 10MB limit', 'error');
        return;
      }
      const ext = f.name.toLowerCase().split('.').pop();
      if (!ext || !['pdf', 'docx', 'txt'].includes(ext)) {
        notify(isBn ? 'অসমর্থিত ফরম্যাট' : 'Unsupported format. Use PDF, DOCX, or TXT', 'error');
        return;
      }
      setFile(f);
      setResult(null);
      setError(null);
    },
    [notify, isBn]
  );

  const onDrop = (e: React.DragEvent) => {
    e.preventDefault();
    setDragOver(false);
    const f = e.dataTransfer.files?.[0];
    if (f) handleFile(f);
  };

  const removeFile = () => {
    setFile(null);
    setResult(null);
    setError(null);
    setProgress(0);
  };

  const analyze = async () => {
    if (!file) return;
    setAnalyzing(true);
    setError(null);
    setProgress(10);

    try {
      // Simulate upload progress
      const interval = setInterval(() => {
        setProgress((p) => Math.min(p + 15, 80));
      }, 150);

      const text = await extractTextFromFile(file);
      clearInterval(interval);
      setProgress(100);

      // Simple keyword-based analysis
      const words = text.split(/\s+/).filter(Boolean);
      const lower = text.toLowerCase();
      const terms = extractTerms(lower);
      const concerns = detectConcerns(lower);

      const summary = isBn
        ? `ডকুমেন্টটিতে প্রায় ${words.length} শব্দ রয়েছে। মূল বিষয়বস্তু: ${terms.slice(0, 3).join(', ') || 'সাধারণ পাঠ্য'}। এটি একটি স্বয়ংক্রিয় ডেমো বিশ্লেষণ এবং আইনি পরামর্শের বিকল্প নয়।`
        : `The document contains approximately ${words.length} words. Key topics: ${terms.slice(0, 3).join(', ') || 'general text'}. This is an automated demo analysis and not a substitute for legal review.`;

      setResult({
        fileName: file.name,
        fileSize: file.size,
        extractedText: text,
        summary,
        terms,
        concerns,
        ts: Date.now(),
      });
      notify(isBn ? 'বিশ্লেষণ সম্পন্ন' : 'Analysis complete', 'success');
    } catch (err) {
      setError(err instanceof Error ? err.message : t('extractionFailed'));
      notify(t('extractionFailed'), 'error');
    } finally {
      setAnalyzing(false);
      setTimeout(() => setProgress(0), 500);
    }
  };

  const downloadReport = () => {
    if (!result) return;
    const report = `DOCUMENT ANALYSIS REPORT
Generated: ${new Date(result.ts).toLocaleString()}
File: ${result.fileName}
Size: ${formatFileSize(result.fileSize)}

[DEMO ANALYSIS - NOT LEGAL ADVICE]

SUMMARY:
${result.summary}

IMPORTANT TERMS:
${result.terms.map((t, i) => `${i + 1}. ${t}`).join('\n')}

POTENTIAL LEGAL CONCERNS:
${result.concerns.map((c, i) => `${i + 1}. ${c}`).join('\n') || 'None detected by automated scan.'}

---
This report was generated by BD Legal Assistant as a demo. Always consult a qualified lawyer.

EXTRACTED TEXT (first 2000 chars):
${result.extractedText.slice(0, 2000)}`;
    downloadTextFile(`analysis-${result.fileName.replace(/\.[^.]+$/, '')}.txt`, report);
  };

  return (
    <div className="space-y-5">
      <PageHeader title={t('docAnalyzerTitle')} subtitle={t('docAnalyzerSubtitle')} icon={<FileSearch size={20} />} />

      <div className="grid lg:grid-cols-2 gap-5">
        {/* Upload */}
        <Card>
          <CardBody>
            {!file ? (
              <div
                onDragOver={(e) => {
                  e.preventDefault();
                  setDragOver(true);
                }}
                onDragLeave={() => setDragOver(false)}
                onDrop={onDrop}
                onClick={() => inputRef.current?.click()}
                className={`flex flex-col items-center justify-center rounded-xl border-2 border-dashed cursor-pointer transition py-12 ${
                  dragOver ? 'border-gold bg-gold-soft/20' : 'border-navy/15 hover:border-gold/40 hover:bg-surface'
                }`}
              >
                <UploadCloud size={36} className="text-muted mb-3" />
                <p className={`text-sm font-medium text-navy ${isBn ? 'bn' : ''}`}>{t('dropHere')}</p>
                <p className={`text-xs text-muted mt-1 ${isBn ? 'bn' : ''}`}>{t('orBrowse')}</p>
                <p className="text-xs text-muted/70 mt-3">{t('supportedFormats')}</p>
                <input
                  ref={inputRef}
                  type="file"
                  className="hidden"
                  accept=".pdf,.docx,.txt"
                  onChange={(e) => {
                    const f = e.target.files?.[0];
                    if (f) handleFile(f);
                  }}
                />
              </div>
            ) : (
              <div className="space-y-4">
                <div className="flex items-center gap-3 rounded-xl bg-surface p-3">
                  <div className="flex h-10 w-10 items-center justify-center rounded-lg bg-navy text-gold shrink-0">
                    <FileText size={18} />
                  </div>
                  <div className="flex-1 min-w-0">
                    <p className="text-sm font-medium text-navy truncate">{file.name}</p>
                    <p className="text-xs text-muted">{formatFileSize(file.size)}</p>
                  </div>
                  <button onClick={removeFile} className="btn-ghost p-2 text-red-600 hover:bg-red-50" aria-label={t('removeFile')}>
                    <X size={16} />
                  </button>
                </div>

                {analyzing && (
                  <div>
                    <div className="flex items-center justify-between text-xs text-muted mb-1">
                      <span className={isBn ? 'bn' : ''}>{t('analyzing')}</span>
                      <span>{progress}%</span>
                    </div>
                    <div className="h-2 rounded-full bg-surface overflow-hidden">
                      <div className="h-full bg-gold transition-all duration-200" style={{ width: `${progress}%` }} />
                    </div>
                  </div>
                )}

                {error && (
                  <div className="flex items-start gap-2 rounded-xl bg-red-50 p-3 text-sm text-red-700">
                    <AlertTriangle size={16} className="mt-0.5 shrink-0" />
                    <p className={isBn ? 'bn' : ''}>{error}</p>
                  </div>
                )}

                {!analyzing && !result && !error && (
                  <Button onClick={analyze} variant="primary" className="w-full">
                    <FileSearch size={15} /> {isBn ? 'বিশ্লেষণ শুরু করুন' : 'Start Analysis'}
                  </Button>
                )}

                {result && (
                  <div className="space-y-2">
                    <Button onClick={downloadReport} variant="gold" className="w-full">
                      <Download size={15} /> {t('downloadReport')}
                    </Button>
                    <button onClick={removeFile} className="btn-ghost w-full text-sm">
                      {isBn ? 'অন্য ফাইল আপলোড করুন' : 'Upload another file'}
                    </button>
                  </div>
                )}
              </div>
            )}
          </CardBody>
        </Card>

        {/* Results */}
        <div>
          {!result && !analyzing && (
            <Card>
              <EmptyState icon={<FileSearch size={28} />} title={t('noAnalysis')} />
            </Card>
          )}
          {analyzing && (
            <Card>
              <CardBody className="flex flex-col items-center justify-center py-16">
                <Loader2 size={28} className="text-gold animate-spin mb-3" />
                <p className={`text-sm text-muted ${isBn ? 'bn' : ''}`}>{t('analyzing')}</p>
              </CardBody>
            </Card>
          )}
          {result && (
            <div className="space-y-3 animate-fadeIn">
              <div className="flex items-center justify-between">
                <Badge variant="success"><CheckCircle2 size={11} /> {isBn ? 'বিশ্লেষণ সম্পন্ন' : 'Analyzed'}</Badge>
                <DemoLabel />
              </div>
              <Card><CardBody>
                <h4 className={`text-sm font-semibold text-navy mb-2 ${isBn ? 'bn' : ''}`}>{t('analysisSummary')}</h4>
                <p className={`text-sm text-ink leading-relaxed ${isBn ? 'bn' : ''}`}>{result.summary}</p>
              </CardBody></Card>
              <Card><CardBody>
                <h4 className={`text-sm font-semibold text-navy mb-2 ${isBn ? 'bn' : ''}`}>{t('importantTerms')}</h4>
                <div className="flex flex-wrap gap-2">
                  {result.terms.length ? result.terms.map((term, i) => (
                    <Badge key={i} variant="default">{term}</Badge>
                  )) : <p className="text-sm text-muted">—</p>}
                </div>
              </CardBody></Card>
              <Card><CardBody>
                <h4 className={`text-sm font-semibold text-navy mb-2 ${isBn ? 'bn' : ''}`}>{t('legalConcerns')}</h4>
                {result.concerns.length ? (
                  <ul className="space-y-1.5">
                    {result.concerns.map((c, i) => (
                      <li key={i} className={`flex gap-2 text-sm text-ink ${isBn ? 'bn' : ''}`}>
                        <AlertTriangle size={14} className="text-gold-dark mt-0.5 shrink-0" />
                        <span>{c}</span>
                      </li>
                    ))}
                  </ul>
                ) : (
                  <p className={`text-sm text-muted ${isBn ? 'bn' : ''}`}>{isBn ? 'স্বয়ংক্রিয় স্ক্যানে কোনো উদ্বেগ সনাক্ত হয়নি।' : 'No concerns detected by automated scan.'}</p>
                )}
              </CardBody></Card>
              <Card><CardBody>
                <h4 className={`text-sm font-semibold text-navy mb-2 ${isBn ? 'bn' : ''}`}>{isBn ? 'নিষ্কাশিত পাঠ্য (প্রিভিউ)' : 'Extracted Text (preview)'}</h4>
                <div className="max-h-40 overflow-y-auto scrollbar-thin rounded-lg bg-surface p-3 text-xs text-muted whitespace-pre-wrap">
                  {result.extractedText.slice(0, 800)}
                  {result.extractedText.length > 800 && '...'}
                </div>
              </CardBody></Card>
            </div>
          )}
        </div>
      </div>
    </div>
  );
}

function extractTerms(text: string): string[] {
  const keywords = [
    'agreement', 'contract', 'party', 'parties', 'payment', 'rent', 'lease',
    'termination', 'clause', 'liability', 'warranty', 'confidential',
    'jurisdiction', 'arbitration', 'indemnify', 'breach', 'obligation',
    'চুক্তি', 'প্রদান', 'দায়', 'বাতিল', 'শর্ত',
  ];
  const found = new Set<string>();
  keywords.forEach((k) => {
    if (text.includes(k)) found.add(k);
  });
  return Array.from(found).slice(0, 8);
}

function detectConcerns(text: string): string[] {
  const concerns: string[] = [];
  if (text.includes('automatically renew')) concerns.push('Automatic renewal clause detected — check termination terms.');
  if (text.includes('non-compete') || text.includes('non compete')) concerns.push('Non-compete clause present — review scope and duration.');
  if (text.includes('indemnify') || text.includes('indemnification')) concerns.push('Indemnification clause present — understand your liability.');
  if (text.includes('arbitration')) concerns.push('Arbitration clause may limit court access for disputes.');
  if (text.includes('confidential')) concerns.push('Confidentiality obligations — review duration and scope.');
  if (text.includes('penalty') || text.includes('forfeit')) concerns.push('Penalty/forfeiture terms detected — verify they are reasonable.');
  return concerns.slice(0, 5);
}
